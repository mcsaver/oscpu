// 显存模块 (vmem)
// 中文说明：
// - 该模块提供一个帧缓冲（显存），把预先生成的像素数据加载到内部存储中，
//   并根据来自 `vga_ctrl` 的像素坐标输出对应像素的 24-bit RGB 数据。
// - 输入：`h_addr`（水平像素坐标，10 位，0..639）和 `v_addr`（垂直像素坐标，9 位，0..479）。
// - 输出：`vga_data` 为 24 位颜色，格式是 {R[7:0], G[7:0], B[7:0]}。
// - 内部存储 `vga_mem` 的深度为 524288（2^19），足够存放 640*480 = 307200 个像素（该设计预留更多地址空间）。
// 
// 关键改进（地址映射修复）：
// - 原始实现使用位拼接 `{h_addr, v_addr}`，等价于 `(h_addr << 9) | v_addr`，
//   这会产生每行 512 个地址步长的映射，与实际 640 宽度不匹配，导致图像扫描线失真。
// - 现在采用**行优先（Row-Major）**映射：index = v_addr * 640 + h_addr
//   这与标准的二维数组行优先存储一致，正确反映 hex 文件的逐行像素顺序。
// - 映射正确性说明：
//   * 第 0 行（v=0）的像素存在地址 0~639（h=0~639）
//   * 第 1 行（v=1）的像素存在地址 640~1279（h=0~639）
//   * 第 y 行的第 x 个像素在地址 y*640+x
//   这样能够准确对应 image.hex 文件中像素的存储位置。
// - 位宽计算：v_addr(9位) * 640 + h_addr(10位) 的最大值为 479*640+639 = 307199 < 2^19 = 524288，
//   因此使用 19 位中间结果 addr_index 足够容纳所有地址。

module vmem(
    input [9:0] h_addr,
    input [8:0] v_addr,
    output [23:0] vga_data
);


// 每个地址存储 24-bit 像素数据（R,G,B 各 8 位）
reg [23:0] vga_mem [524287:0];
initial begin
    // 从十六进制文本文件初始化显存，文件路径相对于仿真/运行目录
    $readmemh("resource/image.hex", vga_mem);
end

// 地址计算：行优先存储，每行 640 个像素
// 
// 为什么这个映射是正确的：
// 1. 像素顺序：image.hex 文件采用行优先存储，即所有第 0 行像素（0..639）依次存放，
//    然后是第 1 行像素（640..1279），以此类推到第 479 行。
// 2. 地址公式：index = v_addr * 640 + h_addr
//    - v_addr：行号（0..479），每行跨越 640 个地址
//    - h_addr：列号（0..639），在行内的偏移
//    - 乘积 v_addr * 640 定位到该行的起始地址，加上 h_addr 得到该行内的精确位置
// 3. 位宽考量：
//    - v_addr 为 9 位（0..511），h_addr 为 10 位（0..1023）
//    - 乘积 v_addr * 640 最大为 479 * 640 = 306560（< 2^19 = 524288）
//    - 加上 h_addr 最多为 306560 + 639 = 307199（仍 < 2^19）
//    - 因此 19 位的 addr_index 足以容纳所有合法地址
// 4. 与扫描失真的关系：
//    - 原来的位拼接 {h_addr, v_addr} 等价于 (h_addr << 9) | v_addr，每行步长为 512
//    - 这导致每行读取 512 个地址，但实际像素宽度为 640，造成行内地址错位
//    - 新的乘法映射每行步长恰好为 640，完全对应 hex 文件的布局，解决了扫描线失真

wire [18:0] addr_index;
assign addr_index = v_addr * 19'd640 + {9'b0, h_addr};
assign vga_data = vga_mem[addr_index];

endmodule
