#!/usr/bin/env python3
"""Discard selected completed-round simulation products, retaining diagnostics."""
import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import re
import shlex
import sys

from finish_round import WORKSPACE, active_builds, regular_file, validate_round_dir, write_json_new


def child_path(directory, value, *, must_exist=True):
    """Select a strict descendant; never follow aliases or parent traversal."""
    raw = Path(value)
    if ".." in raw.parts:
        raise ValueError(f"parent traversal is not allowed: {value}")
    path = raw if raw.is_absolute() else directory / raw
    if path == directory or not path.is_relative_to(directory):
        raise ValueError(f"product must be inside the selected round: {value}")
    current = directory
    for part in path.relative_to(directory).parts:
        current /= part
        if current.is_symlink():
            raise ValueError(f"symlink path is not allowed: {current}")
    if must_exist and not path.exists():
        raise ValueError(f"selected product does not exist: {path}")
    if path.resolve(strict=must_exist) != path:
        raise ValueError(f"selected product is not canonical: {path}")
    return path


def prefix_bytes(path, count=4096):
    with path.open("rb") as stream:
        return stream.read(count)


def plan_obj(directory, selected):
    """Use Verilator's target list, never a recursive obj-directory deletion."""
    obj = child_path(directory, selected)
    if not obj.is_dir():
        raise ValueError(f"expected a Verilator object directory: {obj}")
    manifests = sorted(obj.glob("V*__verFiles.dat"))
    if not manifests:
        raise ValueError(f"no Verilator target/command metadata in: {obj}")
    products, metadata, sources, targets, commands = set(), set(), set(), set(), []
    prefixes = []
    for manifest in manifests:
        regular_file(manifest)
        contents = manifest.read_text()
        if not contents.startswith("# DESCRIPTION: Verilator output:"):
            raise ValueError(f"unrecognized Verilator metadata: {manifest}")
        prefixes.append(manifest.name.removesuffix("__verFiles.dat"))
        metadata.add(manifest)
        for line in contents.splitlines():
            if line.startswith("C "):
                commands.append({"metadata": str(manifest.relative_to(directory)),
                                 "verilator_arguments": shlex.split(line)[1:]})
            if not line.startswith(("S ", "T ")):
                continue
            fields = shlex.split(line)
            path = Path(fields[-1])
            if not path.is_absolute():
                path = obj / path
            if line.startswith("S "):
                sources.add(path.resolve())
                continue
            target = child_path(directory, path, must_exist=False)
            if target.parent != obj:
                raise ValueError(f"Verilator target is outside the selected obj directory: {target}")
            if target.suffix not in {".cpp", ".h", ".mk", ".dat", ".d"}:
                raise ValueError(f"unexpected Verilator generated target: {target}")
            targets.add(target)
    # Unknown contents, nested directories, source inputs, logs and guest files stay.
    for path in sorted(obj.iterdir()):
        generated = path in targets or path.suffix in {".o", ".a", ".gch", ".d"}
        if path.name in prefixes:
            regular_file(path)
            generated = prefix_bytes(path, 4) == b"\x7fELF"
        if any(path.name == prefix + "__ALL.cpp" for prefix in prefixes):
            regular_file(path)
            generated = prefix_bytes(path).startswith(
                b"// DESCRIPTION: Generated by verilator_includer via makefile")
        if path.resolve() in sources:
            generated = False
        if not generated:
            continue
        child_path(directory, path)
        if not regular_file(path):
            continue
        products.add(path)
        if path.name.endswith(("__verFiles.dat", "__ver.d", ".mk")):
            metadata.add(path)
    return products, metadata, commands, obj


def plan_vvp(directory, selected):
    path = child_path(directory, selected)
    if path.suffix != ".vvp" or not regular_file(path):
        raise ValueError(f"expected an explicit .vvp simulator: {path}")
    header = prefix_bytes(path)
    if not header.startswith(b"#!") or b"vvp" not in header.splitlines()[0] or b":ivl_version" not in header:
        raise ValueError(f"not an Icarus VVP generated program: {path}")
    return path


def main(argv=None, *, workspace=WORKSPACE):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--round-dir", required=True,
                        help="one completed round below workspace build/; no historical traversal")
    parser.add_argument("--obj-dir", action="append", default=[],
                        help="Verilator obj directory relative to round-dir; repeatable")
    parser.add_argument("--vvp", action="append", default=[],
                        help="one .vvp program relative to round-dir; repeatable")
    parser.add_argument("--vvp-dir", action="append", default=[],
                        help="inspect .vvp files directly in this directory only; repeatable")
    parser.add_argument("--command-file", action="append", default=[],
                        help="existing run/build command metadata to retain and reference; repeatable")
    parser.add_argument("--upstream-exit-code", type=int,
                        help="record and return original build/test exit code (0..255)")
    parser.add_argument("--dry-run", action="store_true", help="no writes and no deletions")
    args = parser.parse_args(argv)
    original_code = args.upstream_exit_code
    if original_code is not None and not 0 <= original_code <= 255:
        parser.error("--upstream-exit-code must be in 0..255")
    if not (args.obj_dir or args.vvp or args.vvp_dir):
        parser.error("select at least one --obj-dir, --vvp or --vvp-dir")
    try:
        directory = validate_round_dir(args.round_dir, workspace)
        products, metadata, obj_dirs, commands = set(), set(), set(), []
        for selected in args.obj_dir:
            obj_products, obj_metadata, obj_commands, obj = plan_obj(directory, selected)
            products.update(obj_products)
            metadata.update(obj_metadata)
            obj_dirs.add(obj)
            commands.extend(obj_commands)
        vvp_names = list(args.vvp)
        for selected in args.vvp_dir:
            location = child_path(directory, selected)
            if not location.is_dir():
                raise ValueError(f"expected a directory: {location}")
            vvp_names.extend(sorted(location.glob("*.vvp")))
        products.update(plan_vvp(directory, selected) for selected in vvp_names)
        command_files = []
        for selected in args.command_file:
            path = child_path(directory, selected)
            regular_file(path)
            if path in products:
                raise ValueError(f"command metadata cannot be a generated product: {path}")
            command_files.append(str(path.relative_to(directory)))
        # Scope checks to selected objects/products, so independent builds may run.
        active = []
        for target in obj_dirs | {path for path in products if path.parent not in obj_dirs}:
            active.extend(active_builds(target))
        if active:
            raise ValueError(f"build/simulation processes still reference selected products: {active}")
        products = sorted(products)
        states = {path: path.stat() for path in products}
        records = [{"path": str(path.relative_to(directory)), "bytes": states[path].st_size}
                   for path in products]
        report = {"round_dir": str(directory), "upstream_exit_code": original_code,
                  "mode": "dry-run" if args.dry_run else "results-only",
                  "selection": {"obj_dirs": args.obj_dir, "vvp": args.vvp,
                                "vvp_dirs": args.vvp_dir},
                  "retained_command_files": command_files, "build_commands": commands,
                  "preserved_metadata": [], "products": records,
                  "planned_bytes": sum(row["bytes"] for row in records),
                  "removed": [], "reclaimed_bytes": 0,
                  "note": "Cleanup status is not a functional PASS. Existing results, logs, sources, guest images and oracles are unchanged."}
        if args.dry_run:
            print(json.dumps(report, indent=2, ensure_ascii=False))
            return original_code or 0
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S.%fZ")
        base = f"finish-simulation-{stamp}-{os.getpid()}"
        report_path = directory / (base + ".json")
        # Copy commands, source/target metadata and make arguments before deleting.
        for path in sorted(metadata):
            target = directory / base / path.relative_to(directory)
            target.parent.mkdir(parents=True, exist_ok=True)
            with target.open("xb") as output:
                output.write(path.read_bytes())
            report["preserved_metadata"].append(str(target.relative_to(directory)))
        write_json_new(report_path, report)
        cleanup_error = None
        try:
            for path, record in zip(products, records):
                child_path(directory, path)
                regular_file(path)
                current, previous = path.stat(), states[path]
                if (current.st_ino, current.st_size, current.st_mtime_ns) != (
                        previous.st_ino, previous.st_size, previous.st_mtime_ns):
                    raise ValueError(f"product changed during cleanup: {path}")
                path.unlink()
                report["removed"].append(record)
                report["reclaimed_bytes"] += record["bytes"]
            for obj in sorted(obj_dirs):
                if not any(obj.iterdir()):
                    obj.rmdir()
        except (OSError, ValueError) as error:
            cleanup_error = str(error)
            report["error"] = cleanup_error
        report["cleanup_complete"] = cleanup_error is None
        report_path.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
        print(json.dumps(report, indent=2, ensure_ascii=False))
        return original_code or (1 if cleanup_error else 0)
    except (OSError, ValueError) as error:
        print(f"finish_simulation: {error}", file=sys.stderr)
        return original_code or 1


if __name__ == "__main__":
    sys.exit(main())
