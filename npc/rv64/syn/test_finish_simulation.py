#!/usr/bin/env python3
"""Tests of simulation cleanup's actual deletion and evidence boundaries."""
import contextlib
import io
import json
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest
from unittest import mock

import finish_simulation as finish


class FinishSimulation(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.workspace = Path(self.temp.name)
        self.round = self.workspace / "build/ecos-opt-20261012/round1-credit"
        self.obj = self.round / "system/obj"
        self.obj.mkdir(parents=True)

    def tearDown(self):
        self.temp.cleanup()

    def run_finish(self, *args):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = finish.main(["--round-dir", str(self.round), *args],
                               workspace=self.workspace)
        return code, out.getvalue(), err.getvalue()

    def obj_fixture(self):
        names = ["VTop.cpp", "VTop.h", "VTop.mk", "VTop_classes.mk",
                 "VTop__ver.d", "VTop__verFiles.dat"]
        for name in names:
            (self.obj / name).write_text("generated")
        # Source input inside obj is explicitly protected even if listed as T too.
        (self.obj / "original.cpp").write_text("hand-written harness")
        manifest = '# DESCRIPTION: Verilator output: Timestamp data\nC "--cc --assert --threads 1"\n'
        for name in names + ["original.cpp"]:
            manifest += f'T 1 2 3 4 5 6 "{self.obj / name}"\n'
        manifest += f'S 1 2 3 4 5 6 "{self.obj / "original.cpp"}"\n'
        (self.obj / "VTop__verFiles.dat").write_text(manifest)
        for name in ["VTop.o", "VTop.d", "harness.o", "harness.d", "VTop__ALL.a",
                     "VTop__pch.h.fast.gch"]:
            (self.obj / name).write_bytes(b"build product")
        (self.obj / "VTop__ALL.cpp").write_text(
            "// DESCRIPTION: Generated by verilator_includer via makefile\n")
        shutil.copyfile("/bin/sleep", self.obj / "VTop")
        (self.obj / "VTop").chmod(0o755)
        return self.obj / "VTop"

    def vvp_fixture(self, relative="directed/test.vvp"):
        path = self.round / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text('#! /usr/bin/vvp\n:ivl_version "12";\n.scope module;\n')
        return path

    def test_selected_products_removed_metadata_saved_and_failure_unchanged(self):
        self.obj_fixture()
        vvp = self.vvp_fixture()
        keep = [self.round / "run-command.json", self.round / "FAIL.log",
                self.obj / "source.v", self.obj / "original.cpp", self.obj / "guest.elf",
                self.obj / "oracle.json", self.obj / "diagnostic.log"]
        for path in keep:
            path.write_text("original FAIL evidence or source")
        nested = self.obj / "another-round"
        nested.mkdir()
        (nested / "keep.o").write_bytes(b"independent")
        before = {path: path.read_bytes() for path in keep}
        code, output, _ = self.run_finish("--obj-dir", "system/obj", "--vvp-dir", "directed",
                                         "--command-file", "run-command.json",
                                         "--upstream-exit-code", "7")
        report = json.loads(output)
        self.assertEqual(code, 7)
        self.assertEqual(report["upstream_exit_code"], 7)
        self.assertTrue(report["cleanup_complete"])
        self.assertEqual(report["reclaimed_bytes"], report["planned_bytes"])
        self.assertEqual(before, {path: path.read_bytes() for path in keep})
        self.assertFalse(vvp.exists())
        self.assertFalse((self.obj / "VTop").exists())
        self.assertFalse((self.obj / "VTop.cpp").exists())
        self.assertFalse((self.obj / "VTop__ALL.cpp").exists())
        self.assertTrue((nested / "keep.o").exists())
        saved = [self.round / path for path in report["preserved_metadata"]]
        self.assertEqual(len(saved), 4)
        self.assertTrue(all(path.is_file() for path in saved))
        self.assertIn("--assert", report["build_commands"][0]["verilator_arguments"][0])
        self.assertEqual(report["retained_command_files"], ["run-command.json"])

    def test_dry_run_does_not_write_delete_or_rewrite_exit_code(self):
        self.obj_fixture()
        before = {path: path.read_bytes() for path in self.round.rglob("*") if path.is_file()}
        code, output, _ = self.run_finish("--obj-dir", "system/obj", "--dry-run",
                                         "--upstream-exit-code", "2")
        self.assertEqual(code, 2)
        self.assertGreater(json.loads(output)["planned_bytes"], 0)
        after = {path: path.read_bytes() for path in self.round.rglob("*") if path.is_file()}
        self.assertEqual(before, after)

    def test_vvp_directory_does_not_recurse_or_touch_sibling_round(self):
        selected = self.vvp_fixture()
        nested = self.vvp_fixture("directed/old-round/old.vvp")
        sibling = self.round.parent / "round2-other"
        sibling.mkdir()
        (sibling / "guest.bin").write_bytes(b"keep")
        code, _, _ = self.run_finish("--vvp-dir", "directed")
        self.assertEqual(code, 0)
        self.assertFalse(selected.exists())
        self.assertTrue(nested.exists())
        self.assertEqual((sibling / "guest.bin").read_bytes(), b"keep")

    def test_traversal_sibling_symlink_and_fake_vvp_rejected_before_deletion(self):
        self.obj_fixture()
        vvp = self.vvp_fixture()
        sibling = self.round.parent / "round2-other"
        sibling.mkdir()
        external = sibling / "external.vvp"
        external.write_bytes(vvp.read_bytes())
        alias = self.round / "alias.vvp"
        alias.symlink_to(external)
        fake = self.round / "source.vvp"
        fake.write_text("hand-written source")
        for selected in ["../round2-other/external.vvp", str(external), "alias.vvp", "source.vvp"]:
            with self.subTest(selected=selected):
                code, _, _ = self.run_finish("--obj-dir", "system/obj", "--vvp", selected)
                self.assertNotEqual(code, 0)
                self.assertTrue((self.obj / "VTop.cpp").exists())
                self.assertTrue(external.exists())
        obj_alias = self.round / "obj-alias"
        obj_alias.symlink_to(self.obj, target_is_directory=True)
        code, _, _ = self.run_finish("--obj-dir", "obj-alias")
        self.assertNotEqual(code, 0)

    def test_invalid_obj_or_target_symlink_rejected_before_deletion(self):
        self.obj_fixture()
        victim = self.round / "oracle.json"
        victim.write_text("keep")
        (self.obj / "VTop.o").unlink()
        (self.obj / "VTop.o").symlink_to(victim)
        code, _, _ = self.run_finish("--obj-dir", "system/obj")
        self.assertNotEqual(code, 0)
        self.assertTrue((self.obj / "VTop.cpp").exists())
        self.assertEqual(victim.read_text(), "keep")
        empty = self.round / "unknown-obj"
        empty.mkdir()
        (empty / "source.cpp").write_text("keep")
        code, _, _ = self.run_finish("--obj-dir", "unknown-obj")
        self.assertNotEqual(code, 0)
        self.assertTrue((empty / "source.cpp").exists())

    def test_manifest_cannot_delete_target_outside_selected_obj(self):
        self.obj_fixture()
        manifest = self.obj / "VTop__verFiles.dat"
        target = self.round / "manual.cpp"
        target.write_text("keep")
        with manifest.open("a") as stream:
            stream.write(f'T 1 2 3 4 5 6 "{target}"\n')
        code, _, _ = self.run_finish("--obj-dir", "system/obj")
        self.assertNotEqual(code, 0)
        self.assertTrue((self.obj / "VTop.cpp").exists())
        self.assertTrue(target.exists())

    def test_running_generated_binary_detected_outside_round_cwd(self):
        binary = self.obj_fixture()
        process = subprocess.Popen([str(binary), "30"], cwd="/")
        try:
            code, _, errors = self.run_finish("--obj-dir", "system/obj")
            self.assertNotEqual(code, 0)
            self.assertIn("still reference selected products", errors)
            self.assertTrue(binary.exists())
        finally:
            process.terminate()
            process.wait(timeout=5)

    def test_active_vvp_preserves_products_and_original_failure(self):
        vvp = self.vvp_fixture()
        with vvp.open("rb") as stream:
            process = subprocess.Popen(["vvp", "30"], executable="/bin/sleep",
                                       cwd="/", stdin=stream)
        try:
            code, _, errors = self.run_finish("--vvp", "directed/test.vvp",
                                              "--upstream-exit-code", "3")
            self.assertEqual(code, 3)
            self.assertIn("still reference selected products", errors)
            self.assertTrue(vvp.exists())
        finally:
            process.terminate()
            process.wait(timeout=5)

    def test_cleanup_error_keeps_original_failure_and_diagnostics(self):
        self.vvp_fixture()
        with mock.patch.object(Path, "unlink", side_effect=OSError("deliberate filesystem failure")):
            code, output, _ = self.run_finish("--vvp", "directed/test.vvp",
                                              "--upstream-exit-code", "4")
        report = json.loads(output)
        self.assertEqual(code, 4)
        self.assertFalse(report["cleanup_complete"])
        self.assertIn("filesystem failure", report["error"])
        self.assertEqual(report["reclaimed_bytes"], 0)


if __name__ == "__main__":
    unittest.main()
