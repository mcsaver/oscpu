// Physical memory endpoint: owns split sequencing, CPU/PTE arbitration,
// source routing, cache and external bus leases. Client tokens are opaque;
// neither the CPU requester nor composition layer decodes routing bits.
module R64PhysicalMemory #(
  parameter TOKEN_W = 5,
  parameter CACHE_SET_W = 6,
  parameter AUX = 4,
  parameter SRC_W = 3,
  parameter CPU_PREPARE_HINTS = 0,
  parameter PREPARE_ID_W = TOKEN_W
) (
  input cpu_prepare_valid_i,
  input [PREPARE_ID_W-1:0] cpu_prepare_id_i, cpu_identity_i,
  input [TOKEN_W-1:0] cpu_prepare_token_i,
  input [63:0] cpu_prepare_addr_i, cpu_prepare_data_i,
  input [2:0] cpu_prepare_size_i,
  input [7:0] cpu_prepare_strb_i,
  input [4:0] cpu_prepare_amo_i,
  input clk_i, rst_i, invalidate_i, reservation_clear_i,
  input [1:0] cpu_valid_i,
  output [1:0] cpu_ready_o,
  input [2*TOKEN_W-1:0] cpu_token_i,
  input [127:0] cpu_addr_i, cpu_data_i,
  input [3:0] cpu_op_i,
  input [1:0] cpu_cache_i,
  input [5:0] cpu_size_i,
  input [15:0] cpu_strb_i,
  input [9:0] cpu_amo_i,
  input [1:0] cpu_fast_store_i,
  output [1:0] cpu_rsp_valid_o,
  input [1:0] cpu_rsp_ready_i,
  output [2*TOKEN_W-1:0] cpu_rsp_token_o,
  output [127:0] cpu_rsp_data_o,
  output [1:0] cpu_rsp_error_o,
  output [5:0] cpu_rsp_offset_o,
  output cpu_store_rsp_valid_o,
  input cpu_store_rsp_ready_i,
  output [TOKEN_W-1:0] cpu_store_rsp_token_o,
  output cpu_store_rsp_error_o,
  output idle_o,
  input  [            AUX-1:0] aux_valid_i,
  output [            AUX-1:0] aux_ready_o,
  input  [         AUX*64-1:0] aux_addr_i, aux_data_i, aux_expected_i,
  input  [          AUX*2-1:0] aux_op_i,
  input  [            AUX-1:0] aux_cache_i,
  input  [          AUX*3-1:0] aux_size_i,
  input  [          AUX*8-1:0] aux_strb_i,
  output [            AUX-1:0] aux_rsp_valid_o,
  input  [            AUX-1:0] aux_rsp_ready_i,
  output [         AUX*64-1:0] aux_rsp_data_o,
  output [            AUX-1:0] aux_rsp_error_o, aux_rsp_compare_o,
  output                       read_valid_o,
  input                        read_ready_i,
  output [               63:0] read_addr_o,
  output [                7:0] read_len_o,
  output [                2:0] read_size_o,
  input                        beat_valid_i,
  output                       beat_ready_o,
  input  [               63:0] beat_data_i,
  input  [                1:0] beat_resp_i,
  input                        beat_last_i,
  output                       write_valid_o,
  input                        write_ready_i,
  output [               63:0] write_addr_o,
  output [                2:0] write_size_o,
  output                       write_data_valid_o,
  input                        write_data_ready_i,
  output [               63:0] write_data_o,
  output [                7:0] write_strb_o,
  input                        write_rsp_valid_i,
  output                       write_rsp_ready_o,
  input  [                1:0] write_resp_i
);
  localparam CT = TOKEN_W + SRC_W;
  wire [1:0] sfast, kfast;
  wire cache_store_valid_w, cache_store_ready_w, cache_store_error_w;
  wire [CT-1:0] cache_store_token_w;
  wire [1:0] sv, sr, scv, scr, se, scached;
  wire [2*TOKEN_W-1:0] st, sct;
  wire [127:0] sa, sd, scd;
  wire [3:0] so;
  wire [5:0] sz;
  wire [15:0] ss;
  wire [9:0] sm;
  wire split_idle_w, service_idle_w, cache_idle_w;
  wire [1:0] service_request_w;
  wire [1:0] kv, kr, kcv, kcr, ke, kcompare, kcached;
  wire [2*CT-1:0] kt, kct;
  wire [127:0] ka, kd, kexpected, kcd;
  wire [3:0] ko;
  wire [5:0] kz;
  wire [15:0] ks;
  wire [9:0] km;
  wire unused_mutation_w;
  wire [60:0] unused_mutation_word_w;
  assign idle_o = split_idle_w && service_idle_w && cache_idle_w;
  R64MemorySplit #(
    .TOKEN_W(TOKEN_W)
  ) split (
    .clk_i(clk_i),
    .rst_i(rst_i),
    .physical_idle_i(service_idle_w && cache_idle_w),
    .idle_o(split_idle_w),
    .in_fast_store_i(cpu_fast_store_i),
    .out_fast_store_o(sfast),
    .in_valid_i(cpu_valid_i),
    .in_ready_o(cpu_ready_o),
    .in_token_i(cpu_token_i),
    .in_addr_i(cpu_addr_i),
    .in_data_i(cpu_data_i),
    .in_op_i(cpu_op_i),
    .in_cache_i(cpu_cache_i),
    .in_size_i(cpu_size_i),
    .in_strb_i(cpu_strb_i),
    .in_amo_i(cpu_amo_i),
    .rsp_valid_o(cpu_rsp_valid_o),
    .rsp_ready_i(cpu_rsp_ready_i),
    .rsp_token_o(cpu_rsp_token_o),
    .rsp_data_o(cpu_rsp_data_o),
    .rsp_error_o(cpu_rsp_error_o),
    .rsp_offset_o(cpu_rsp_offset_o),
    .out_valid_o(sv),
    .out_request_o(service_request_w),
    .out_ready_i(sr),
    .out_token_o(st),
    .out_addr_o(sa),
    .out_data_o(sd),
    .out_op_o(so),
    .out_cache_o(scached),
    .out_size_o(sz),
    .out_strb_o(ss),
    .out_amo_o(sm),
    .mem_rsp_valid_i(scv),
    .mem_rsp_ready_o(scr),
    .mem_rsp_token_i(sct),
    .mem_rsp_data_i(scd),
    .mem_rsp_error_i(se)
  );
  R64MemoryService #(
    .TOKEN_W(TOKEN_W),
    .AUX(AUX),
    .SRC_W(SRC_W),
    .CPU_REQUEST_HINTS(1),
    .CPU_READ_EMPTY_FLOW(1),
    .CPU_PREPARE_HINTS(CPU_PREPARE_HINTS),
    .PREPARE_ID_W(PREPARE_ID_W)
  ) service (
    .cpu_prepare_valid_i(cpu_prepare_valid_i),
    .cpu_prepare_id_i(cpu_prepare_id_i),
    .cpu_prepare_token_i(cpu_prepare_token_i),
    .cpu_prepare_addr_i(cpu_prepare_addr_i),
    .cpu_prepare_data_i(cpu_prepare_data_i),
    .cpu_prepare_size_i(cpu_prepare_size_i),
    .cpu_prepare_strb_i(cpu_prepare_strb_i),
    .cpu_prepare_amo_i(cpu_prepare_amo_i),
    .cpu_identity_i(cpu_identity_i),
    .cpu_store_rsp_valid_o(cpu_store_rsp_valid_o),
    .cpu_store_rsp_ready_i(cpu_store_rsp_ready_i),
    .cpu_store_rsp_token_o(cpu_store_rsp_token_o),
    .cpu_store_rsp_error_o(cpu_store_rsp_error_o),
    .cache_store_rsp_valid_i(cache_store_valid_w),
    .cache_store_rsp_ready_o(cache_store_ready_w),
    .cache_store_rsp_token_i(cache_store_token_w),
    .cache_store_rsp_error_i(cache_store_error_w),
    .cpu_fast_store_i(sfast),
    .cache_fast_store_o(kfast),
    .clk_i(clk_i),
    .rst_i(rst_i),
    .cpu_valid_i(sv),
    .cpu_request_i(service_request_w),
    .cpu_ready_o(sr),
    .cpu_token_i(st),
    .cpu_addr_i(sa),
    .cpu_data_i(sd),
    .cpu_op_i(so),
    .cpu_cache_i(scached),
    .cpu_size_i(sz),
    .cpu_strb_i(ss),
    .cpu_amo_i(sm),
    .cpu_rsp_valid_o(scv),
    .cpu_rsp_ready_i(scr),
    .cpu_rsp_token_o(sct),
    .cpu_rsp_data_o(scd),
    .cpu_rsp_error_o(se),
    .aux_valid_i(aux_valid_i),
    .aux_ready_o(aux_ready_o),
    .aux_addr_i(aux_addr_i),
    .aux_data_i(aux_data_i),
    .aux_expected_i(aux_expected_i),
    .aux_op_i(aux_op_i),
    .aux_cache_i(aux_cache_i),
    .aux_size_i(aux_size_i),
    .aux_strb_i(aux_strb_i),
    .aux_rsp_valid_o(aux_rsp_valid_o),
    .aux_rsp_ready_i(aux_rsp_ready_i),
    .aux_rsp_data_o(aux_rsp_data_o),
    .aux_rsp_error_o(aux_rsp_error_o),
    .aux_rsp_compare_o(aux_rsp_compare_o),
    .cache_valid_o(kv),
    .cache_ready_i(kr),
    .cache_token_o(kt),
    .cache_addr_o(ka),
    .cache_data_o(kd),
    .cache_expected_o(kexpected),
    .cache_op_o(ko),
    .cache_cache_o(kcached),
    .cache_size_o(kz),
    .cache_strb_o(ks),
    .cache_amo_o(km),
    .cache_rsp_valid_i(kcv),
    .cache_rsp_ready_o(kcr),
    .cache_rsp_token_i(kct),
    .cache_rsp_data_i(kcd),
    .cache_rsp_error_i(ke),
    .cache_rsp_compare_i(kcompare),
    .idle_o(service_idle_w)
  );
  R64Dcache #(
    .SET_W  (CACHE_SET_W),
    .TOKEN_W(CT)
  ) cache (
    .clk_i(clk_i),
    .rst_i(rst_i),
    .invalidate_i(invalidate_i),
    .reservation_clear_i(reservation_clear_i),
    .req_fast_store_i(kfast),
    .store_rsp_valid_o(cache_store_valid_w),
    .store_rsp_ready_i(cache_store_ready_w),
    .store_rsp_token_o(cache_store_token_w),
    .store_rsp_error_o(cache_store_error_w),
    .req_valid_i(kv),
    .req_ready_o(kr),
    .req_token_i(kt),
    .req_addr_i(ka),
    .req_data_i(kd),
    .req_expected_i(kexpected),
    .req_op_i(ko),
    .req_cache_i(kcached),
    .req_size_i(kz),
    .req_strb_i(ks),
    .req_amo_i(km),
    .rsp_valid_o(kcv),
    .rsp_ready_i(kcr),
    .rsp_token_o(kct),
    .rsp_data_o(kcd),
    .rsp_error_o(ke),
    .rsp_compare_o(kcompare),
    .read_valid_o(read_valid_o),
    .read_ready_i(read_ready_i),
    .read_addr_o(read_addr_o),
    .read_len_o(read_len_o),
    .read_size_o(read_size_o),
    .beat_valid_i(beat_valid_i),
    .beat_ready_o(beat_ready_o),
    .beat_data_i(beat_data_i),
    .beat_resp_i(beat_resp_i),
    .beat_last_i(beat_last_i),
    .write_valid_o(write_valid_o),
    .write_ready_i(write_ready_i),
    .write_addr_o(write_addr_o),
    .write_size_o(write_size_o),
    .write_data_valid_o(write_data_valid_o),
    .write_data_ready_i(write_data_ready_i),
    .write_data_o(write_data_o),
    .write_strb_o(write_strb_o),
    .write_rsp_valid_i(write_rsp_valid_i),
    .write_rsp_ready_o(write_rsp_ready_o),
    .write_resp_i(write_resp_i),
    .idle_o(cache_idle_w),
    .mutation_o(unused_mutation_w),
    .mutation_word_o(unused_mutation_word_w)
  );
endmodule
